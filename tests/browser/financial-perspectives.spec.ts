import { expect, test } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { mkdir } from "node:fs/promises";
test("movement and saved custom scenarios reconcile, preserve frozen sources and remain isolated on mobile", async ({ page, baseURL }) => {
  const runtimeErrors: string[] = [];
  page.on("pageerror", (error) => runtimeErrors.push(error.message));
  page.on("console", (message) => {
    if (message.type() === "error" && !message.text().startsWith("Failed to load resource")) runtimeErrors.push(message.text());
  });
  const origin = new URL(baseURL!).origin;
  async function post(path: string, data: unknown) {
    const response = await page.request.post(path, { headers: { origin }, data });
    expect(response.ok(), await response.text()).toBe(true);
    return (await response.json()).data;
  }
  const password = "A-scenario-test-password-123!", email = `scenarios-${randomUUID()}@example.test`;
  await post("/api/auth", { action: "register", email, password, display_name: "Scenario owner" });
  await post("/api/auth", { action: "login", email, password });
  const w = randomUUID(), path = `/api/workspaces/${w}`;
  await post("/api/workspaces", { id: w, name: "Scenario studio", kind: "business", functional_currency_code: "USD", timezone: "UTC" });
  const bank = randomUUID(), foreign = randomUUID(), capital = randomUUID(), revenue = randomUUID(), expense = randomUUID();
  for (const [id, name, type, currency_code] of [[bank, "USD bank", "asset", "USD"], [foreign, "SGD bank", "asset", "SGD"], [capital, "Capital", "equity", null], [revenue, "Services", "revenue", null], [expense, "Costs", "expense", null]])
    await post(`${path}/accounts`, { id, name, type, currency_code, role: "general", is_active: true });
  function line(account_id: string, side: string, amount: string) { return { id: randomUUID(), account_id, side, amount, book_amount: amount, currency_code: "USD", exchange_rate: "1", rate_source: null }; }
  async function entry(description: string, date: string, lines: unknown[], posted = true) {
    const id = randomUUID(); await post(`${path}/events`, { post: posted, event: { id, accounting_date: date, kind: "adjustment", description, party_id: null, lines, obligation: null, settlements: [] } }); return id;
  }
  await entry("Opening capital", "2026-09-01", [line(bank, "debit", "1000"), line(capital, "credit", "1000")]);
  await entry("Earlier services", "2026-09-10", [line(bank, "debit", "100"), line(revenue, "credit", "100")]);
  await entry("Earlier foreign services", "2026-09-15", [
    { ...line(foreign, "debit", "100"), currency_code: "SGD", book_amount: "75", exchange_rate: "0.75", rate_source: "manual" },
    { ...line(revenue, "credit", "100"), currency_code: "SGD", book_amount: "75", exchange_rate: "0.75", rate_source: "manual" },
  ]);
  const original = await entry("Reversed costs", "2026-10-01", [line(expense, "debit", "50"), line(bank, "credit", "50")]);
  await entry("October services", "2026-10-02", [line(bank, "debit", "200"), line(revenue, "credit", "200")]);
  await post(`${path}/reversals`, { original, reversal: randomUUID(), on_date: "2026-10-03" });
  await entry("Draft costs", "2026-10-05", [line(expense, "debit", "999"), line(bank, "credit", "999")], false);
  await entry("Future services", "2026-11-01", [line(bank, "debit", "900"), line(revenue, "credit", "900")]);
  const ledgerBefore = (await (await page.request.get(path)).json()).data;
  await page.goto("/");
  await page.getByRole("button", { name: "Activity", exact: true }).click();
  await page.getByLabel("Search entries").fill("stale");
  await page.getByLabel("Account", { exact: true }).selectOption(bank);
  await page.getByLabel("Status", { exact: true }).selectOption("draft");
  await page.getByRole("button", { name: "Reports", exact: true }).click();
  await page.getByLabel("From date").fill("2026-10-01"); await page.getByLabel("Through date").fill("2026-10-31");
  const presentation = page.getByRole("group", { name: "Report presentation", exact: true });
  await presentation.getByRole("button", { name: "Movement", exact: true }).click();
  const movement = page.getByRole("region", { name: "Balance sheet movement", exact: true });
  await expect(movement.getByRole("row", { name: /Total assets/ })).toContainText("USD 1,175.00");
  await expect(movement.getByRole("row", { name: /Total assets/ })).toContainText("USD 200.00");
  await expect(movement.getByRole("row", { name: /Total assets/ })).toContainText("USD 1,375.00");
  await movement.getByRole("button", { name: "Total assets, opening: USD 1,175.00", exact: true }).click();
  await expect(page.getByLabel("Activity view")).toHaveValue("balance_sheet");
  await expect(page.getByLabel("As of date")).toHaveValue("2026-09-30");
  await expect(page.getByLabel("Search entries")).toHaveValue("");
  await page.getByRole("button", { name: "← Back to Reports", exact: true }).click();
  await expect(presentation.getByRole("button", { name: "Movement", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByLabel("From date")).toHaveValue("2026-10-01");
  await expect(page.getByLabel("Through date")).toHaveValue("2026-10-31");
  await movement.getByRole("button", { name: "Total assets, movement: USD 200.00", exact: true }).click();
  await expect(page.getByLabel("Activity view")).toHaveValue("balance_movement");
  await expect(page.getByLabel("Report group")).toHaveValue("asset");
  await expect(page.getByRole("region", { name: "Complete report totals", exact: true })).toContainText("USD 200.00");
  await page.locator(".report-account summary").filter({ hasText: "USD bank" }).click();
  const journals = page.getByRole("region", { name: "USD bank journal lines", exact: true });
  await expect(journals).toContainText("October services"); await expect(journals).not.toContainText("Earlier services");
  await expect(journals).not.toContainText("Draft costs"); await expect(journals).not.toContainText("Future services");
  await page.getByRole("button", { name: "← Back to Reports", exact: true }).click();
  await mkdir("test-results/visual", { recursive: true });
  await page.screenshot({ path: "test-results/visual/balance-movement-desktop.png", fullPage: true });
  await presentation.getByRole("button", { name: "Scenarios", exact: true }).click();
  await page.getByRole("button", { name: "New scenario", exact: true }).click();
  const sheet = page.getByRole("dialog", { name: "Create financial scenario", exact: true });
  await expect(sheet).toHaveClass(/dialog-sheet/);
  await sheet.getByLabel("Scenario name").fill("Baseline replay");
  await expect(sheet).toContainText("3 selected"); await expect(sheet).not.toContainText("Draft costs");
  await expect(sheet).toContainText("SGD 100.00");
  await sheet.getByRole("button", { name: "Save scenario", exact: true }).click();
  await expect(sheet).not.toBeVisible();
  const results = page.getByRole("region", { name: "Scenario results", exact: true });
  await expect(results).toContainText("Baseline replay");
  await expect(results.getByRole("button", { name: /Scenario profit/ })).toContainText("USD 200.00");
  await expect(movement.getByRole("button", { name: "Total assets, closing: USD 1,375.00", exact: true })).toBeVisible();
  await page.getByRole("region", { name: "Frozen replay entries" }).getByRole("button", { name: /October services/ }).click();
  const frozenSheet = page.getByRole("dialog", { name: "Frozen scenario entry", exact: true });
  await expect(frozenSheet).toHaveClass(/dialog-sheet/); await expect(frozenSheet).toContainText("USD 200.00");
  await expect(frozenSheet.getByRole("button", { name: /Reverse|Edit/ })).toHaveCount(0);
  await page.keyboard.press("Escape");
  expect((await (await page.request.get(path)).json()).data).toEqual(ledgerBefore);
  const baselineList = (await (await page.request.get(`${path}/scenarios`)).json()).data;
  const baselineId = baselineList[0].id;
  await entry("Added after capture", "2026-10-10", [line(bank, "debit", "7"), line(revenue, "credit", "7")]);
  await page.reload(); await page.getByRole("button", { name: "Reports", exact: true }).click();
  await presentation.getByRole("button", { name: "Scenarios", exact: true }).click();
  await page.getByLabel("Choose scenario").selectOption(baselineId);
  await expect(results.getByRole("button", { name: /Scenario profit/ })).toContainText("USD 200.00");
  await expect(page.getByRole("region", { name: "Frozen replay entries" })).not.toContainText("Added after capture");
  await results.getByRole("button", { name: /Scenario profit/ }).click();
  await expect(page.getByRole("region", { name: "Frozen scenario detail" })).toContainText("USD 200.00");
  await page.getByRole("button", { name: "← Back to scenario", exact: true }).click();
  await page.getByRole("button", { name: "New scenario", exact: true }).click();
  await sheet.getByLabel("Scenario name").fill("Extra capital");
  await sheet.getByLabel("Scenario start date").fill("2026-10-01"); await sheet.getByLabel("Scenario end date").fill("2026-10-31");
  await sheet.getByLabel("Opening position").selectOption("custom");
  await sheet.getByLabel("USD bank opening (USD)", { exact: true }).fill("-");
  await expect(sheet).toContainText("Complete the balance amounts");
  await sheet.getByLabel("USD bank opening (USD)", { exact: true }).fill("2100");
  await sheet.getByRole("button", { name: "Save scenario", exact: true }).click();
  await expect(sheet.getByRole("alert")).toContainText("must equal");
  await sheet.getByLabel("Capital opening (USD)", { exact: true }).fill("2000");
  await sheet.getByLabel("Added after capture", { exact: false }).uncheck();
  await sheet.getByRole("button", { name: "Save scenario", exact: true }).click();
  await expect(results).toContainText("Extra capital");
  await expect(results.getByRole("button", { name: /Scenario profit/ })).toContainText("USD 200.00");
  await expect(movement.getByRole("button", { name: "Total assets, closing: USD 2,375.00", exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Switch color theme", exact: true }).click();
  await expect(page.locator("html")).toHaveClass(/dark/);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/visual/scenario-mobile-dark.png", fullPage: true });
  await results.getByRole("button", { name: "Delete scenario", exact: true }).click();
  await expect(results).not.toBeVisible();
  await page.getByLabel("Choose scenario").selectOption(baselineId);
  await expect(results).toContainText("Baseline replay");
  const second = randomUUID(); await post("/api/workspaces", { id: second, name: "Empty personal", kind: "personal", functional_currency_code: "THB", timezone: "UTC" });
  await page.reload(); await page.getByLabel("Current workspace").selectOption(second);
  await page.getByRole("button", { name: "Reports", exact: true }).click();
  await presentation.getByRole("button", { name: "Scenarios", exact: true }).click();
  await expect(page.getByRole("heading", { name: "No saved scenarios", exact: true })).toBeVisible();
  await expect(page.getByLabel("Choose scenario")).toHaveCount(0);
  await page.getByRole("button", { name: "New scenario", exact: true }).click();
  await sheet.getByLabel("Scenario name").fill("Opening only");
  await sheet.getByRole("button", { name: "Save scenario", exact: true }).click();
  await expect(results).toContainText("THB 0.00");
  await expect(page.getByRole("region", { name: "Frozen replay entries" })).toContainText("Opening-only scenario");
  expect(runtimeErrors).toEqual([]);
});
