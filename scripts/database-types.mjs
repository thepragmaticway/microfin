import { writeFile, readdir, readFile } from "node:fs/promises";
// Parse the migration's declared column types, preserving the numeric-as-text
// wire contract. Regenerate whenever schema columns change.
const sql = (
  await Promise.all(
    (await readdir("supabase/migrations"))
      .filter((x) => x.endsWith(".sql"))
      .sort()
      .map((x) => readFile(`supabase/migrations/${x}`, "utf8")),
  )
).join("\n");
const tables = {};
for (const [, name, body] of sql.matchAll(
  /create table public\.(\w+)\s*\(([\s\S]*?)\n\);/g,
)) {
  tables[name] = [];
  for (const line of body.split("\n")) {
    const m = line
      .trim()
      .match(
        /^(\w+) (uuid|text|varchar\(\d+\)|numeric\(\d+,\d+\)|smallint|boolean|timestamptz|date)(?=\s|,|$)/,
      );
    if (!m) continue;
    const [, column, type] = m,
      nullable = !/not null|primary key/.test(line);
    tables[name].push(
      `    ${column}: ${type === "boolean" ? "boolean" : type === "smallint" ? "number" : "string"}${nullable ? " | null" : ""};`,
    );
  }
}
const output = `// Generated by npm run db:types from versioned migrations.\nexport interface DatabaseRows {\n${Object.entries(
  tables,
)
  .map(([name, columns]) => `  ${name}: {\n${columns.join("\n")}\n  };`)
  .join("\n")}\n}\n`;
await writeFile("src/lib/database.generated.ts", output);
console.log(`Generated ${Object.keys(tables).length} table row contracts`);
